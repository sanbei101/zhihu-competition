/**
 * 直接给玩家看的文本的语言纪律。
 *
 * 这是整套推演里最容易被忽略、却又最影响观感的一条规则:
 * summary / conclusion / narrator / hint / intent 全是玩家逐字读的,
 * 模型一旦写成书面报告腔,整个世界就会显得"像教科书而不像正在发生的事"。
 * 所以统一在这里钉死一句:**写人话,写短句,写具体的物。**
 */
export const PLAIN_TEXT = `
语言风格(summary、conclusion、hint、intent、narrator 等所有直接给玩家看的文字都必须遵守):
- 用大白话写,像人转述一件正在发生的事。不写书面语、不写公文腔、不写新闻通稿。
- 短句,一句只说一件事。禁用"该""乃""犹""此等""故""继而""态势""格局""加剧""蔓延"这类词。
- 不排比,不堆四字成语,不做结论性升华("由此可见""历史将证明""这标志着")。
- 写动作和具体的物:写"征发了三千石粮"而不是"加大资源动员力度",写"城里的米价翻了三倍"而不是"经济状况恶化"。
- summary 只白描发生了什么,不写评价、不写前因后果。
- hint 是选项的代价预告,用半句话点破后果,像酒桌上一句提醒,不说教。
- conclusion 用一句话说清"谁得了什么、谁付了什么"。
`;

