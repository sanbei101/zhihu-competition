/**
 * 数值与列表的填写纪律。
 *
 * 这一段是为了解决一类具体的浪费:模型把"赋役压力"写成 120,而展示量纲是 0-100,
 * 校验直接失败,一份本来很好的推演被丢掉,玩家白等一轮。
 * 与其事后补救,不如事前说清楚:范围是软的,服务端会兜住,你按自己的判断写就行。
 */
export const WORLD_FORMAT_RULES = `
关于数值与列表的填写:
- 所有 0-100 的数值(指标值、亲疏度等)只是**表达力刻度**,不是精确统计。按你的判断给一个
  大致位置即可,不要为了凑数而牺牲判断。若某个量在现实里远超 100(如人口数以万计),
  请把真实口径写进 unit,value 仍然给 0-100 的刻度。
- 列表长度是建议值,不是硬性配额。宁可少写几条写实的,也不要为凑数量重复或空话。
- 数值与列表的轻微越界由系统自动处理,不会影响你的输出被采纳。不要因为纠结格式而改变判断。`;

/** 所有调用点共享的输出纪律 */
export const WORLD_DISCIPLINE = `
通用纪律:
- 全部使用简体中文。专名、制度名、地名要具体,不要写"某个势力""某个技术"这类空指代。
- 这是推演,不是爽文。禁止出现主角光环、天降奇才、无视后勤与制度成本的胜利。
- 不要写对话,不要写台词,不要写"某某说"。这里记录的是力量与后果,不是剧本。
  (唯一的例外是见证者的 narrator 字段 —— 它本来就是一句人话,规则见下。)
- 不要引用现代概念去解释前现代世界(除非这个主题本身就是现代或未来)。
${WORLD_FORMAT_RULES}`;

