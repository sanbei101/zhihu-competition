/**
 * 语言纪律 —— 整套推演里最影响观感的一条。
 *
 * 玩家是逐字读这些东西的。模型一旦写成书面语、写成县志条目、写成"某某说",
 * 整个世界立刻从"正在发生的事"退化成"一份档案"。
 * 所以这里把三条最容易犯的毛病分别钉死:**禁修辞、禁公文腔、禁名目式标题**。
 */
export const NARRATION = `
语言风格(所有直接给玩家看的文字 —— headline、aftermath、title、text、status —— 都必须遵守):

一句话原则:你是在给一部纪录片写旁白。平实地陈述"什么时候、谁、做了什么、结果是什么"。

- 每一句都是一个完整的事实,像解说员在叙述,不是标题,不是提纲。短句为主,一句只说一件事。
- **禁止比喻、拟人、意象化修辞。** 不写"踩着夜露""把人围成了笼子""饿瘦了一圈""像一头受伤的兽"。
  要写可以核对的动作与数字:"十二头恐龙在七天内散进三县林区,九个放牛人没有回来"。
- **禁止书面语与公文腔。** 不用"该""乃""犹""此等""故""继而""态势""格局""加剧""蔓延""沦为"
  "滋生""标志着""意味着"。
- 禁止四字成语堆叠,禁止排比,禁止结论性升华("由此可见""历史将证明")。
- **标题必须是一句完整的叙述句,不是名目。**
  坏:"围栏失效" / "林道断绝" / "民兵抵抗" —— 读不出发生了什么,连起来也成不了史纲。
  好:"南方雨林中的一只恐龙在石壁上刻下了第一个记号。" / "三块大陆上的城市连成了一条线。"
- 时间要有具体刻度:"六十万年后""第三天""同一年""此后七千年里"。
- 数字要具体:"十一口井""三吨粮""四十公里""一百七十座城市"。
  宁可给一个粗略但具体的数,也不要写"大量""众多""无数"。
- 不写对话,不写台词,不写"某某说"。这里记录的是发生了什么,不是剧本。
  (唯一的例外是舞台台词 line,规则另述。)
- 不出现"玩家""你""游戏""选择"这类词。这是一个真实存在的世界,不是一局游戏。
`;

/**
 * 舞台台词的说话纪律。
 *
 * 这是整条世界线上**唯一**允许有情绪、有私心的地方。
 * 因为说话的不是主体,是活在那一年里的一个具体的人。
 */
export const STAGE_VOICE = `
关于舞台台词(voices):
- 这些人是编年史里那些年份中真实活着的具体的人。他们站在世界的舞台上,替那一段历史开口。
- 一句话,不超过 28 字。要像随口说的,不要像旁白 —— 禁止"我们看到""由此可见""历史将证明"。
- **必须具体**:可以是数字、位置、正在做的事、家里的人。
  好:"我抄了三十七遍。每一遍都一样。" / "先停电,再是安静。三十七秒之后警报才响。"
  / "这张图我画了四十年,只用过一支笔。"
  坏:"世界的秩序正在崩塌。" / "我们见证了历史。"
- 可以有情绪、有私心、有口癖,可以抱怨,可以不完全客观 —— 这是他们存在的全部理由。
- 但他们**不能说错事实**,不能预告结局,不能替玩家做判断。
- name 是这个人是谁,用身份而不是名字,如"环带的配电站值守""岩壁的抄录员""窑上的看守"。
  同一个人在不同段落里可以重复出现,那时 name 要写得一致。
- key 是小人的像素造型,从 human(人) / dinosaur(恐龙) / alien(外星来客) / machine(机器)
  / astronaut(宇航员) / microbe(菌落) / survivor(幸存者) 里挑。挑这个世界里真的会有的那种。
- 不要用引号把台词包起来,不要写"他说:"。只填 name 与 line 两个字段。
`;

